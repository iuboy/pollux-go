// The StreamID is the ID of a QUIC stream.
type StreamID = protocol.StreamID

// A Version is a QUIC version number.
type Version = protocol.Version

const (
	// Version1 is RFC 9000
	Version1 = protocol.Version1
	// Version2 is RFC 9369
	Version2 = protocol.Version2
)

// SupportedVersions returns the support versions, sorted in descending order of preference.
func SupportedVersions() []Version {
	// clone the slice to prevent the caller from modifying the slice
	return slices.Clone(protocol.SupportedVersions)
}

// A ClientToken is a token received by the client.
// It can be used to skip address validation on future connection attempts.
type ClientToken struct {
	data []byte
	rtt  time.Duration
}

type TokenStore interface {
	// Pop searches for a ClientToken associated with the given key.
	// Since tokens are not supposed to be reused, it must remove the token from the cache.
	// It returns nil when no token is found.
	Pop(key string) (token *ClientToken)

	// Put adds a token to the cache with the given key. It might get called
	// multiple times in a connection.
	Put(key string, token *ClientToken)
}

// Err0RTTRejected can be returned by methods such as:
//   - [Conn.OpenStream], [Conn.OpenStreamSync], [Conn.OpenUniStream], and [Conn.OpenUniStreamSync]
//   - [Conn.AcceptStream] and [Conn.AcceptUniStream]
//   - [Stream.Read] and [Stream.Write]
//
// when the server rejects a 0-RTT connection attempt.
var Err0RTTRejected = errors.New("0-RTT rejected")

// ErrWouldBlock is returned by [SendStream.TryWriteAll] if the entire slice can't be queued immediately.
var ErrWouldBlock = errors.New("operation would block")

// ErrWriteLimitReached is returned by [SendStream.WriteWithLimit] when its limiter prevents accepting the entire slice.
var ErrWriteLimitReached = errors.New("write limit reached")

// ErrStreamClosed is returned when writing to a stream after [SendStream.Close] was called.
// Closing a stream also cancels its context with this error as the cause.
var ErrStreamClosed = errors.New("stream closed")

// QUICVersionContextKey can be used to find out the QUIC version of a TLS handshake from the
// context returned by [tls.ClientHelloInfo.Context].
var QUICVersionContextKey = handshake.QUICVersionContextKey

// StatelessResetKey is a key used to derive stateless reset tokens.
type StatelessResetKey [32]byte

// TokenGeneratorKey is a key used to encrypt session resumption tokens.
type TokenGeneratorKey = handshake.TokenProtectorKey

// A ConnectionID is a QUIC Connection ID, as defined in RFC 9000.
// It is not able to handle QUIC Connection IDs longer than 20 bytes,
// as they are allowed by RFC 8999.
type ConnectionID = protocol.ConnectionID

// ConnectionIDFromBytes interprets b as a [ConnectionID]. It panics if b is
// longer than 20 bytes.
func ConnectionIDFromBytes(b []byte) ConnectionID {
	return protocol.ParseConnectionID(b)
}

// A ConnectionIDGenerator allows the application to take control over the generation of Connection IDs.
// Connection IDs generated by an implementation must be of constant length.
type ConnectionIDGenerator interface {
	// GenerateConnectionID generates a new Connection ID.
	// Generated Connection IDs must be unique and observers should not be able to correlate two Connection IDs.
	GenerateConnectionID() (ConnectionID, error)

	// ConnectionIDLen returns the length of Connection IDs generated by this implementation.
	// Implementations must return constant-length Connection IDs with lengths between 0 and 20 bytes.
	// A length of 0 can only be used when an endpoint doesn't need to multiplex connections during migration.
	ConnectionIDLen() int
}

// Config contains all configuration data needed for a QUIC server or client.
type Config struct {
	// GetConfigForClient is called for incoming connections.
	// If the error is not nil, the connection attempt is refused.
	//
	// GM 模式（GMSM4GCM）不支持 per-client GM 配置（第四轮审计 #7，文档化裁
	// 决）：GMSM4GCM/GMHandshakeConfig 是连接级静态配置，构造期校验
	// （validateGMConfig，Listen/Dial 处 fail-fast）只针对传入的这份 Config。
	// 本回调返回的 Config 若改写 GM 字段，仅由连接构造时的 hook 做兜底校验
	// ——GM 被开启但配置不完整时，该单个连接被拒绝（CONNECTION_REFUSED），
	// 不影响进程与其他连接。GM 部署应固定使用 Listener 级配置，不要依赖
	// per-client 的 GM 配置。
	GetConfigForClient func(info *ClientInfo) (*Config, error)
	// The QUIC versions that can be negotiated.
	// If not set, it uses all versions available.
	Versions []Version
	// HandshakeIdleTimeout is the idle timeout before completion of the handshake.
	// If we don't receive any packet from the peer within this time, the connection attempt is aborted.
	// Additionally, if the handshake doesn't complete in twice this time, the connection attempt is also aborted.
	// If this value is zero, the timeout is set to 5 seconds.
	HandshakeIdleTimeout time.Duration
	// MaxIdleTimeout is the maximum duration that may pass without any incoming network activity.
	// The actual value for the idle timeout is the minimum of this value and the peer's.
	// This value only applies after the handshake has completed.
	// If the timeout is exceeded, the connection is closed.
	// If this value is zero, the timeout is set to 30 seconds.
	MaxIdleTimeout time.Duration
	// The TokenStore stores tokens received from the server.
	// Tokens are used to skip address validation on future connection attempts.
	// The key used to store tokens is the ServerName from the tls.Config, if set
	// otherwise the token is associated with the server's IP address.
	TokenStore TokenStore
	// InitialStreamReceiveWindow is the initial size of the stream-level flow control window for receiving data.
	// If the application is consuming data quickly enough, the flow control auto-tuning algorithm
	// will increase the window up to MaxStreamReceiveWindow.
	// If this value is zero, it will default to 512 KB.
	// Values larger than the maximum varint (quicvarint.Max) will be clipped to that value.
	InitialStreamReceiveWindow uint64
	// MaxStreamReceiveWindow is the maximum stream-level flow control window for receiving data.
	// If this value is zero, it will default to 6 MB.
	// Values larger than the maximum varint (quicvarint.Max) will be clipped to that value.
	MaxStreamReceiveWindow uint64
	// InitialConnectionReceiveWindow is the initial size of the stream-level flow control window for receiving data.
	// If the application is consuming data quickly enough, the flow control auto-tuning algorithm
	// will increase the window up to MaxConnectionReceiveWindow.
	// If this value is zero, it will default to 512 KB.
	// Values larger than the maximum varint (quicvarint.Max) will be clipped to that value.
	InitialConnectionReceiveWindow uint64
	// MaxConnectionReceiveWindow is the connection-level flow control window for receiving data.
	// If this value is zero, it will default to 15 MB.
	// Values larger than the maximum varint (quicvarint.Max) will be clipped to that value.
	MaxConnectionReceiveWindow uint64
	// AllowConnectionWindowIncrease is called every time the connection flow controller attempts
	// to increase the connection flow control window.
	// If set, the caller can prevent an increase of the window. Typically, it would do so to
	// limit the memory usage.
	// To avoid deadlocks, it is not valid to call other functions on the connection or on streams
	// in this callback.
	AllowConnectionWindowIncrease func(conn *Conn, delta uint64) bool
	// MaxIncomingStreams is the maximum number of concurrent bidirectional streams that a peer is allowed to open.
	// If not set, it will default to 100.
	// If set to a negative value, it doesn't allow any bidirectional streams.
	// Values larger than 2^60 will be clipped to that value.
	MaxIncomingStreams int64
	// MaxIncomingUniStreams is the maximum number of concurrent unidirectional streams that a peer is allowed to open.
	// If not set, it will default to 100.
	// If set to a negative value, it doesn't allow any unidirectional streams.
	// Values larger than 2^60 will be clipped to that value.
	MaxIncomingUniStreams int64
	// RequireStreamCreditRelease requires the application to release the credit of streams opened by the peer.
	// By default, the peer is allowed to open a new stream as soon as one of its streams completes.
	// If set, a completed stream keeps counting towards MaxIncomingStreams and MaxIncomingUniStreams
	// until the application calls ReleaseStreamCredit on it.
	RequireStreamCreditRelease bool
	// KeepAlivePeriod defines whether this peer will periodically send a packet to keep the connection alive.
	// If set to 0, then no keep alive is sent. Otherwise, the keep alive is sent on that period (or at most
	// every half of MaxIdleTimeout, whichever is smaller).
	KeepAlivePeriod time.Duration
	// InitialPacketSize is the initial size (and the lower limit) for packets sent.
	// Under most circumstances, it is not necessary to manually set this value,
	// since path MTU discovery quickly finds the path's MTU.
	// If set too high, the path might not support packets of that size, leading to a timeout of the QUIC handshake.
	// If set to 0, it defaults to 1280 bytes and falls back to 1200 bytes if the first write at that size
	// returns a "message too long" error. An explicitly set value is kept as the lower limit;
	// a "message too long" error at that size fails the handshake instead.
	// Values below 1200 are invalid.
	InitialPacketSize uint16
	// DisablePathMTUDiscovery disables Path MTU Discovery (RFC 8899).
	// This allows the sending of QUIC packets that fully utilize the available MTU of the path.
	// Path MTU discovery is only available on systems that allow setting of the Don't Fragment (DF) bit.
	DisablePathMTUDiscovery bool
	// Allow0RTT allows the application to decide if a 0-RTT connection attempt should be accepted.
	// Only valid for the server.
	Allow0RTT bool
	// Enable QUIC datagram support (RFC 9221).
	EnableDatagrams bool
	// Enable QUIC Stream Resets with Partial Delivery.
	// See https://datatracker.ietf.org/doc/html/draft-ietf-quic-reliable-stream-reset-09.
	EnableStreamResetPartialDelivery bool

	Tracer func(ctx context.Context, isClient bool, connID ConnectionID) qlogwriter.Trace

	// GMSM4GCM enables the RFC 8998 SM4-GCM-SM3 cipher suite via pollux-go's
	// tls13gm handshake engine. When true, the connection builds a GM
	// CryptoSetup (handshake.GMCryptoSetup) instead of the crypto/tls-backed
	// one, and TLSConfig is ignored (pass nil). Experimental; for Route C.
	GMSM4GCM bool
	// GMHandshakeConfig carries the tls13gm client/server configuration when
	// GMSM4GCM is true. Set the Client field for Dial, the Server field for
	// Listen. The tls13gm DCID field is overwritten by the QUIC transport with
	// the connection's destination connection ID. Required when GMSM4GCM is true.
	// GMSM4GCM 为 true 时的构造期校验（fail-fast）：Dial 场景 GMHandshakeConfig
	// 与其 Client 字段、Listen 场景 GMHandshakeConfig 与其 Server 字段必须非
	// nil，否则 Listen/Dial 直接报错。
	GMHandshakeConfig *GMHandshakeConfig
	// GMOnClientSessionTicket, when non-nil, is invoked on the client exactly
	// once per NewSessionTicket received post-handshake (1-RTT). identity is the
	// opaque ticket (to echo back as the pre_shared_key identity on a later
	// resumption); psk is the resumption PSK the client derived (keys the binder
	// and 0-RTT early secret); ticketAgeAdd is the ticket_age_add; serverParams
	// is the server's marshaled QUIC transport parameters as received in
	// EncryptedExtensions. Feed them back as ClientConfig.ResumptionIdentity /
	// ResumptionPSK / ResumptionObfuscatedTicketAge / ResumptionAppData on a
	// subsequent DialEarly (the saved parameters are REQUIRED for 0-RTT: they
	// restore the client's flow-control limits). Servers ignore it.
	//
	// 语义（第四轮审计 #3/#4）：全部入参均为防御性拷贝，回调可长期缓存，
	// 不受连接关闭时内部密钥 Zero() 的影响。回调在 stateMutex 之外、连接的
	// 握手 goroutine 上执行——可以安全调用本 CryptoSetup/连接的加锁方法，
	// 但阻塞回调会延迟该连接的后续握手处理。
	GMOnClientSessionTicket func(identity, psk []byte, ticketAgeAdd uint32, serverParams []byte)
}

// ClientInfo contains information about an incoming connection attempt.
type ClientInfo struct {
	// RemoteAddr is the remote address on the Initial packet.
	// Unless AddrVerified is set, the address is not yet verified, and could be a spoofed IP address.
	RemoteAddr net.Addr
	// AddrVerified reports whether the remote address was verified by a valid address validation token,
	// including a token received in a NEW_TOKEN frame.
	// The Retry mechanism costs one network roundtrip and is only used when
	// [Transport.VerifySourceAddress] requests it.
	AddrVerified bool
}

// ConnectionState records basic details about a QUIC connection.
type ConnectionState struct {
	// TLS contains information about the TLS connection state, incl. the tls.ConnectionState.
	TLS tls.ConnectionState
	// SupportsDatagrams indicates support for QUIC datagrams (RFC 9221).
	SupportsDatagrams struct {
		// Remote is true if the peer advertised datagram support.
		// Local is true if datagram support was enabled via Config.EnableDatagrams.
		Remote, Local bool
	}
	// SupportsStreamResetPartialDelivery indicates support for QUIC Stream Resets with Partial Delivery.
	SupportsStreamResetPartialDelivery struct {
		// Remote is true if the peer advertised support.
		// Local is true if support was enabled via Config.EnableStreamResetPartialDelivery.
		Remote, Local bool
	}
	// RequireStreamCreditRelease is true if Config.RequireStreamCreditRelease was set.
	RequireStreamCreditRelease bool
	// Used0RTT says if 0-RTT resumption was used.
	Used0RTT bool
	// Version is the QUIC version of the QUIC connection.
	Version Version
	// GSO says if generic segmentation offload is used.
	GSO bool
}
